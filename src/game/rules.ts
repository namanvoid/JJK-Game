export function computeComboMultiplier(comboCount: number): number {
  if (comboCount <= 1) return 1.0;
  return Number(Math.min(1.65, 1.0 + (comboCount - 1) * 0.08).toFixed(2));
}

export function computeDynamicHitstun(baseHitstun: number, comboCount: number): number {
  if (baseHitstun <= 0) return 0;
  // Early combo hits get slight hitstun extension so chains feel fluid; deep combos taper to prevent infinite loops
  if (comboCount <= 4) {
    return Number((baseHitstun * (1 + Math.max(0, comboCount - 1) * 0.04)).toFixed(3));
  }
  const decay = Math.max(0.65, 1.12 - (comboCount - 4) * 0.06);
  return Number((baseHitstun * decay).toFixed(3));
}

export interface CameraState {
  zoom: number;
  x: number;
  y: number;
}

export function computeDynamicCamera(
  playerX: number,
  enemyX: number,
  playerY: number,
  enemyY: number,
  current: CameraState,
  dt: number
): CameraState {
  const dist = Math.abs(playerX - enemyX);
  // Close-range clash (<= 85px) zooms in up to 1.26x; pulled back (>= 230px) returns to 1.0x
  const t = Math.max(0, Math.min(1, (230 - dist) / (230 - 85)));
  const targetZoom = 1.0 + t * 0.26;

  const midX = (playerX + enemyX) * 0.5;
  const midY = Math.min(GROUND_Y - 22, (playerY + enemyY) * 0.5 - 26);

  // Clamp focal center so zoomed view stays cleanly inside the 480x270 stage
  const halfViewW = (WORLD_WIDTH * 0.5) / targetZoom;
  const halfViewH = (WORLD_HEIGHT * 0.5) / targetZoom;
  const targetX = Math.max(halfViewW, Math.min(WORLD_WIDTH - halfViewW, midX));
  const targetY = Math.max(halfViewH, Math.min(WORLD_HEIGHT - halfViewH, midY + 18));

  const smooth = Math.min(1, dt * 6.5);
  return {
    zoom: current.zoom + (targetZoom - current.zoom) * smooth,
    x: current.x + (targetX - current.x) * smooth,
    y: current.y + (targetY - current.y) * smooth,
  };
}

export interface HitResolution {
  hit: boolean;
  blocked: boolean;
  parried: boolean;
  infinityBlocked: boolean;
  damage: number;
  hitstun: number;
  knockbackX: number;
  knockbackY: number;
  hitstop: number;
  ceGainAttacker: number;
  ceGainDefender: number;
}

export function resolveHit(
  attacker: Pick<FighterState, 'id' | 'facing' | 'comboCount' | 'buffTimer'>,
  defender: Pick<
    FighterState,
    | 'id'
    | 'action'
    | 'facing'
    | 'invulnTimer'
    | 'blockWindowTimer'
    | 'parryWindowTimer'
    | 'infinityTimer'
    | 'buffTimer'
    | 'superArmorActive'
  >,
  move: MoveSpec,
  difficultyMultiplier = 1
): HitResolution {
  if (defender.invulnTimer > 0 && !move.isUnblockable) {
    return {
      hit: false,
      blocked: false,
      parried: false,
      infinityBlocked: false,
      damage: 0,
      hitstun: 0,
      knockbackX: 0,
      knockbackY: 0,
      hitstop: 0,
      ceGainAttacker: 0,
      ceGainDefender: 0,
    };
  }

  const nextCombo = attacker.comboCount + 1;
  const comboMul = computeComboMultiplier(nextCombo);
  const attackerBuffMul = attacker.buffTimer > 0 ? 1.15 : 1.0;
  const defenderArmorMul =
    defender.buffTimer > 0 && (defender.id === 'panda' || defender.id === 'hanami') ? 0.65 : 1.0;

  const rawDamage = Math.round(
    move.damage * difficultyMultiplier * comboMul * attackerBuffMul * defenderArmorMul
  );
  const rawChip = Math.round(move.chipDamage * difficultyMultiplier * defenderArmorMul);

  // Dedicated Parry stance (Q/F) or fresh Just-Block
  if (
    (defender.parryWindowTimer > 0 || (defender.action === 'block' && defender.blockWindowTimer > 0)) &&
    !move.isUnblockable
  ) {
    return {
      hit: true,
      blocked: true,
      parried: true,
      infinityBlocked: false,
      damage: 0,
      hitstun: 0,
      knockbackX: attacker.facing * 50,
      knockbackY: 0,
      hitstop: 0.075,
      ceGainAttacker: 0,
      ceGainDefender: defender.parryWindowTimer > 0 ? 22 : 18,
    };
  }

  // Gojo's Infinity reduces/deflects non-piercing attacks
  if (
    defender.id === 'gojo' &&
    defender.infinityTimer > 0 &&
    !move.piercesInfinity &&
    !move.isUnblockable
  ) {
    return {
      hit: true,
      blocked: true,
      parried: false,
      infinityBlocked: true,
      damage: 0,
      hitstun: 0,
      knockbackX: attacker.facing * 20,
      knockbackY: 0,
      hitstop: 0.025,
      ceGainAttacker: 0,
      ceGainDefender: 4,
    };
  }

  const isBlocking = defender.action === 'block' && !move.isUnblockable;
  if (isBlocking) {
    return {
      hit: true,
      blocked: true,
      parried: false,
      infinityBlocked: false,
      damage: rawChip,
      hitstun: move.blockstun,
      knockbackX: attacker.facing * move.knockbackX * 0.45,
      knockbackY: 0,
      hitstop: move.hitstop * 0.65,
      ceGainAttacker: Math.round(move.ceGainOnHit * 0.35),
      ceGainDefender: 4,
    };
  }

  if (defender.superArmorActive && !move.isUnblockable) {
    return {
      hit: true,
      blocked: false,
      parried: false,
      infinityBlocked: false,
      damage: Math.round(rawDamage * 0.7),
      hitstun: 0,
      knockbackX: 0,
      knockbackY: 0,
      hitstop: move.hitstop * 0.5,
      ceGainAttacker: move.ceGainOnHit,
      ceGainDefender: 6,
    };
  }

  return {
    hit: true,
    blocked: false,
    parried: false,
    infinityBlocked: false,
    damage: rawDamage,
    hitstun: computeDynamicHitstun(move.hitstun, nextCombo),
    knockbackX: attacker.facing * move.knockbackX,
    knockbackY: move.knockbackY,
    hitstop: move.hitstop,
    ceGainAttacker: move.ceGainOnHit,
    ceGainDefender: 7,
  };
}

export function canChainAttack(
  fighterId: FighterId,
  current: FighterAction,
  next: FighterAction
): boolean {
  const spec = getPlayerMoveSpec(fighterId, current);
  if (!spec || !spec.canChainInto) return false;
  return spec.canChainInto.includes(next);
}

export function computeSukunaPhase(hp: number, maxHp: number): 1 | 2 | 3 {
  const ratio = hp / Math.max(1, maxHp);
  if (ratio <= 0.33) return 3;
  if (ratio <= 0.66) return 2;
  return 1;
}

