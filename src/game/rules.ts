export function computeBluePullVelocity(
  blueX: number,
  blueY: number,
  targetX: number,
  targetY: number,
  strength = 360
): { vx: number; vy: number } {
  const dx = blueX - targetX;
  const dy = blueY - targetY;
  const dist = Math.hypot(dx, dy);
  if (dist < 4 || dist > 160) return { vx: 0, vy: 0 };
  const factor = (1 - dist / 160) * strength;
  return {
    vx: (dx / dist) * factor,
    vy: (dy / dist) * factor * 0.35,
  };
}

export function calculateRoundScore(params: {
  remainingHp: number;
  maxHp: number;
  maxCombo: number;
  timeRemaining: number;
  stageNumber: number;
}): number {
  const hpBonus = Math.round((params.remainingHp / Math.max(1, params.maxHp)) * 1200);
  const comboBonus = params.maxCombo * 140;
  const timeBonus = Math.round(Math.max(0, params.timeRemaining) * 18);
  const stageBonus = params.stageNumber * 500;
  return hpBonus + comboBonus + timeBonus + stageBonus;
}
