export function getPlayerMoveSpec(id: FighterId, action: FighterAction): MoveSpec | null {
  if (BASIC_PLAYER_MOVES[action]) {
    const base = BASIC_PLAYER_MOVES[action];
    if (id === 'panda' || id === 'hanami') {
      return { ...base, damage: Math.round(base.damage * 1.15), range: base.range + 4 };
    }
    if (id === 'yuta') {
      return { ...base, range: base.range + 8 }; // katana reach
    }
    if (id === 'mahito') {
      return { ...base, range: base.range + 10 }; // blade-arm reach
    }
    if (id === 'geto' || id === 'kenjaku') {
      return { ...base, range: base.range + 6 };
    }
    if (id === 'sukuna') {
      return { ...base, damage: Math.round(base.damage * 1.12), range: base.range + 6 };
    }
    if (id === 'megumi' || id === 'kashimo') {
      return { ...base, startup: Math.max(0.05, base.startup - 0.01) };
    }
    if (id === 'toji') {
      return { ...base, startup: Math.max(0.04, base.startup - 0.015), piercesInfinity: true };
    }
    return base;
  }
  return FIGHTER_SKILLS[id]?.[action] || null;
}

